/**
 * Pure TypeScript SHA-256 and HMAC-SHA256 implementation.
 * Self-contained with zero native dependencies to ensure 100% reliable execution
 * in React Native, Expo, and Node.js environments.
 */

function rotr(n: number, x: number): number {
  return (x >>> n) | (x << (32 - n));
}

function choose(x: number, y: number, z: number): number {
  return (x & y) ^ (~x & z);
}

function majority(x: number, y: number, z: number): number {
  return (x & y) ^ (x & z) ^ (y & z);
}

function sigma0(x: number): number {
  return rotr(2, x) ^ rotr(13, x) ^ rotr(22, x);
}

function sigma1(x: number): number {
  return rotr(6, x) ^ rotr(11, x) ^ rotr(25, x);
}

function gamma0(x: number): number {
  return rotr(7, x) ^ rotr(18, x) ^ (x >>> 3);
}

function gamma1(x: number): number {
  return rotr(17, x) ^ rotr(19, x) ^ (x >>> 10);
}

